"""Example dashboards: generator output, rendering rules, no Home Assistant needed."""

import importlib.util
import re
import sys
from pathlib import Path

import pytest
import yaml

EXAMPLES = Path(__file__).resolve().parents[1] / "examples"
# generator arguments of every generated example
GENERATED = {
    "hydro_dashboard_bacchiglione.yaml": [],
    "hydro_dashboard_bacchiglione_it.yaml": ["--lang", "it"],
    "hydro_dashboard_bacchiglione_full.yaml": ["--full"],
    "hydro_dashboard_bacchiglione_full_it.yaml": ["--lang", "it", "--full"],
}
CARD_MOD = "#graph-wrapper { min-width: 0; }"


@pytest.fixture(scope="module")
def generator():
    """Load examples/generate_hydro_dashboard.py as a module."""
    spec = importlib.util.spec_from_file_location("generate_hydro_dashboard", EXAMPLES / "generate_hydro_dashboard.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def render(generator, args):
    """Return the text the generator writes for the given arguments."""
    lang = args[args.index("--lang") + 1] if "--lang" in args else "en"
    view = generator.build_view(lang, "--full" in args)
    header = ("# Generated by examples/generate_hydro_dashboard.py " + " ".join(args)).rstrip() + "\n"
    return header + yaml.safe_dump(view, allow_unicode=True, sort_keys=False, width=200)


def read(name):
    """Return an example file with normalised line endings."""
    return (EXAMPLES / name).read_text(encoding="utf-8").replace("\r\n", "\n")


def walk(node, parents=()):
    """Yield (card, ancestors) for every dict of a loaded YAML tree."""
    if isinstance(node, dict):
        yield node, parents
        for value in node.values():
            yield from walk(value, (*parents, node))
    elif isinstance(node, list):
        for value in node:
            yield from walk(value, parents)


def apex_cards(name):
    """Return (card, ancestors) for every ApexCharts card of an example."""
    view = yaml.safe_load(read(name))
    return [(c, p) for c, p in walk(view) if c.get("type") == "custom:apexcharts-card"]


@pytest.mark.parametrize("name", sorted(GENERATED))
def test_generator_output_equals_committed_example(generator, name):
    """The committed examples are exactly what the generator writes."""
    assert read(name) == render(generator, GENERATED[name])


@pytest.mark.parametrize("name", sorted(GENERATED))
def test_apexcharts_cards_have_no_visibility_and_follow_the_card_width(name):
    """A hidden card with its own visibility never draws: conditions belong on containers."""
    cards = apex_cards(name)
    assert cards
    for card, _ in cards:
        assert "visibility" not in card
        assert card["card_mod"] == {"style": CARD_MOD}
        assert card["series"][0]["float_precision"] == 2
        assert card["apex_config"]["grid"]["strokeDashArray"] == 0
        assert card["apex_config"]["xaxis"]["labels"]["datetimeFormatter"]["second"] == "HH:mm"


def test_no_example_apexcharts_card_has_visibility_at_any_depth():
    """Scan every example YAML, not only the generated ones."""
    for path in sorted(EXAMPLES.glob("*.yaml")):
        for node, _ in walk(yaml.safe_load(path.read_text(encoding="utf-8"))):
            if node.get("type") == "custom:apexcharts-card":
                assert "visibility" not in node, path.name


@pytest.mark.parametrize("name", ["hydro_dashboard_bacchiglione_full.yaml", "hydro_dashboard_bacchiglione_full_it.yaml"])
def test_period_containers_carry_state_and_screen_conditions(name):
    """Per period one vertical stack below 768 px and one horizontal stack from 768 px."""
    containers = [c for c, _ in walk(yaml.safe_load(read(name)))
                  if c.get("type") in ("vertical-stack", "horizontal-stack") and "visibility" in c]
    assert len(containers) == 8
    assert all(c["grid_options"] == {"columns": "full"} and len(c["cards"]) == 7 for c in containers)
    for kind, query in (("vertical-stack", "(max-width: 767px)"), ("horizontal-stack", "(min-width: 768px)")):
        selected = [c for c in containers if c["type"] == kind]
        assert len(selected) == 4
        for c in selected:
            conditions = {v["condition"]: v for v in c["visibility"]}
            assert set(conditions) == {"state", "screen"}
            assert conditions["screen"]["media_query"] == query
    assert len({c["visibility"][0]["state"] for c in containers}) == 4


def test_basic_views_keep_the_layout_switch_on_containers():
    """Views without a period selector switch phone/wide on the containers."""
    for name in ("hydro_dashboard_bacchiglione.yaml", "hydro_dashboard_bacchiglione_it.yaml"):
        containers = [c for c, _ in walk(yaml.safe_load(read(name))) if "visibility" in c]
        assert sorted(c["type"] for c in containers) == ["horizontal-stack", "vertical-stack"]
        assert all([v["condition"] for v in c["visibility"]] == ["screen"] for c in containers)


def test_last_hour_is_drawn_from_the_samples_with_threshold_variants():
    """The last hour uses samples_24h, carries the last value to the end, and cuts at each threshold."""
    cards = [c for c, _ in apex_cards("hydro_dashboard_bacchiglione_full.yaml") if c["graph_span"] == "1h"]
    with_thresholds = [c for c in cards if len(c["series"]) == 4]
    assert len(cards) == 14 and len(with_thresholds) == 10
    for card in cards:
        main = card["series"][0]
        assert "group_by" not in main and "statistics" not in main
        code = main["data_generator"]
        assert "samples_24h" in code and "start.getTime()" in code and "end.getTime()" in code
        assert code.endswith("return out;")
    for card in with_thresholds:
        for series in card["series"][1:]:
            value = re.search(r">= ([\d.]+)", series["name"]).group(1)
            assert f"p[1] >= {value} ? p[1] : null" in series["data_generator"]
            assert "transform" not in series
